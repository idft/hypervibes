import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { LearningConflict } from "./learning-service.js";
import { memoryFixture, researchInput } from "./test-fixture.js";
const scope = { kind: "agent" } as const;
const input = (content: string, extra = {}) => ({ scope, content, reason: "Reusable finding", evidenceRefs: [], ...extra });
describe("versioned accumulated learnings", () => {
  let f: Awaited<ReturnType<typeof memoryFixture>>;
  beforeEach(async () => { f = await memoryFixture(); });
  afterEach(async () => { await f.close(); });
  it("keeps independent scopes, permits authorized reviewer writes, and preserves evidence through appends", async () => {
    const { memory, learning } = f.services();
    expect(await learning.current("agent", scope)).toEqual({ scope, version: 0, content: "" });
    await memory.publishResearch(f.analyst, "evidence", researchInput(f.now));
    expect(await learning.append(f.reviewer, "reviewer-finding", input("General guidance", { evidenceRefs: ["m1"] }))).toEqual({ scope, version: 1 });
    await Promise.all([learning.append(f.reviewer, "append-a", input("Finding A")), learning.append(f.reviewer, "append-b", input("Finding B"))]);
    expect(await learning.current("agent", scope)).toMatchObject({ version: 3, content: "General guidance\n\n---\n\nFinding A\n\n---\n\nFinding B" });
    expect(await learning.revision("agent", scope, 3)).toMatchObject({ evidenceRefs: ["m1"], sourceRunId: "run-reviewer", producerSubagentId: "reviewer", userId: null });
    const worker = { kind: "worker", subagentId: "analyst" };
    await learning.append(f.reviewer, "worker-finding", input("Specific guidance", { scope: worker }));
    expect(await learning.current("agent", worker)).toMatchObject({ version: 1, content: "Specific guidance" });
    expect(await learning.current("other", scope)).toMatchObject({ version: 0, content: "" });
    await expect(learning.append(f.analyst, "no-write-tools", input("Unauthorized"))).rejects.toThrow("permitted");
    await expect(learning.current("agent", { kind: "worker", subagentId: "foreign" })).rejects.toThrow("not found");
    await expect(learning.append(f.reviewer, "foreign-write", input("Unauthorized", { scope: { kind: "worker", subagentId: "foreign" } }))).rejects.toThrow();
    await f.db.run("UPDATE hv_subagents SET archived=1,enabled=0 WHERE id='analyst'");
    expect((await learning.revision("agent", worker, 1)).content).toBe("Specific guidance");
  });
  it("CAS replacement has one winner, audited clears, immutable history, and draft-friendly conflicts", async () => {
    const { learning } = f.services();
    const results = await Promise.allSettled([learning.replace(f.operator, "replace-a", input("First", { expectedVersion: 0 })), learning.replace(f.operator, "replace-b", input("Second", { expectedVersion: 0 }))]);
    expect(results.filter((r) => r.status === "fulfilled")).toHaveLength(1);
    const failed = results.find((r) => r.status === "rejected");
    expect(failed?.status === "rejected" && failed.reason).toBeInstanceOf(LearningConflict);
    await learning.replace(f.operator, "clear", input("", { expectedVersion: 1 }));
    expect(await learning.current("agent", scope)).toMatchObject({ version: 2, content: "" });
    expect((await learning.revision("agent", scope, 1)).content).toBe("First");
    await learning.replace(f.operator, "restore-copy", input("First", { expectedVersion: 2 }));
    expect((await learning.current("agent", scope)).version).toBe(3);
    const page = await learning.history("agent", scope, { limit: 2 });
    expect(page.items.map((r) => r.version)).toEqual([3, 2]);
    expect(page.items[0]).not.toHaveProperty("content");
    expect((await learning.history("agent", scope, { beforeVersion: page.nextBeforeVersion })).items.map((r) => r.version)).toEqual([1]);
  });
  it("replays an earlier committed result after later edits, terminal runs, expiry and reopen", async () => {
    let { learning } = f.services();
    const firstInput = input("Original", { expectedVersion: 0 });
    const original = await learning.replace(f.reviewer, "original", firstInput);
    await learning.append(f.operator, "newer", input("Later finding"));
    await f.db.run("UPDATE hv_subagent_runs SET status='completed' WHERE id='run-reviewer'");
    ({ learning } = await f.reopen());
    expect(await learning.replace(f.reviewer, "original", firstInput)).toEqual(original);
    expect((await learning.current("agent", scope)).version).toBe(2);
    await expect(learning.replace(f.reviewer, "original", { ...firstInput, content: "Changed" })).rejects.toThrow("different");
    await expect(learning.append(f.reviewer, "late", input("Late"))).rejects.toThrow("active");
  });
  it("rejects overflows and missing evidence atomically, without successful receipts or empty sets", async () => {
    const { learning } = f.services();
    await expect(learning.append(f.operator, "missing", input("Finding", { evidenceRefs: ["m9"] }))).rejects.toThrow("not found");
    expect(await f.db.get("SELECT count(*) AS total FROM hv_learning_sets")).toMatchObject({ total: 0 });
    await learning.replace(f.operator, "full", input("x".repeat(8000), { expectedVersion: 0 }));
    await expect(learning.append(f.operator, "overflow", input("One more"))).rejects.toThrow("consolidate");
    expect(await f.db.get("SELECT count(*) AS total FROM hv_learning_revisions")).toMatchObject({ total: 1 });
    expect(await f.db.get("SELECT count(*) AS total FROM hv_memory_operations")).toMatchObject({ total: 1 });
    await expect(learning.replace(f.operator, "stale", input("Draft", { expectedVersion: 0 }))).rejects.toMatchObject({ currentVersion: 1, status: 409 });
    await expect(learning.append(f.operator, "large-append", input("x".repeat(2001)))).rejects.toThrow("2000");
  });
  it("snapshots both heads in a caller-owned transaction and retains copied contents after edits", async () => {
    const { learning } = f.services();
    await learning.append(f.operator, "general", input("General"));
    const snapshots = await f.db.transaction(async (tx) => ({ general: await learning.snapshotTx(tx, "agent", scope), worker: await learning.snapshotTx(tx, "agent", { kind: "worker", subagentId: "analyst" }) }));
    await learning.append(f.operator, "later", input("Later"));
    expect(snapshots.general).toEqual({ scope, version: 1, content: "General" });
    expect(snapshots.worker).toMatchObject({ version: 0, content: "" });
  });
});
